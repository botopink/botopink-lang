%%% ambient `Index<i32, T>` behavior, and the expression's type is whatever the

%%% method answers: `?T`. An index past the end therefore has an answer, and it

%%% is decision 47's one spelling of absent — `null`. Not `undefined`, not `0`,

%%% and not a failure: the earlier reading of decision 63 (the index answers `T`

%%% and an absent one aborts) is the one the amendment replaced, and this cell

%%% is the third spelling C-16 lists as `index_an_index_past_the_end_answers_zero`

%%% — the slug said `zero`, the next text said `undefined`, and the rule says

%%% `null`.

%%% 

%%% `xs.at(9)` — the method called by name — is the SAME feature now, which is

%%% the whole point: there is one reader, and the index is its syntax.

%%% 

