%%% Decision 330 — `f?.(args)` calls the function an optional holds, and is

%%% absent when the optional is, on every target.

adder(Present) ->
    Add = fun(N) ->
        '__bp_int'((N + 1), -2147483648, 2147483647, <<"integer overflow: + on i32 at src/main.bp:7:40">>)
    end,
    case Present of
        true ->
            Add;
        false ->
            undefined
    end.

